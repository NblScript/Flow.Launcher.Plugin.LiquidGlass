using System.Globalization;
using System.IO;
using System.Text;

namespace Flow.Launcher.Plugin.LiquidGlass
{
    /// <summary>
    /// 生成并写入「Liquid Glass」主题文件到 Flow 的用户主题目录（%APPDATA%\FlowLauncher\Themes）。
    /// 主题只负责文字颜色、圆角、选中态等；真正的玻璃底由 GlassController 绘制。
    /// </summary>
    internal static class ThemeWriter
    {
        public const string ThemeFileName = "Liquid Glass";
        public const string ThemeDisplayName = "Liquid Glass";

        public static string GetThemePath(IPublicAPI api) =>
            Path.Combine(api.GetDataDirectory(), "Themes", ThemeFileName + ".xaml");

        /// <returns>文件内容是否发生了变化</returns>
        public static bool Write(IPublicAPI api, Settings s, bool dark)
        {
            var path = GetThemePath(api);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            var xaml = Build(s, dark);
            if (File.Exists(path) && File.ReadAllText(path) == xaml)
                return false;
            File.WriteAllText(path, xaml, new UTF8Encoding(true));
            return true;
        }

        private static string Build(Settings s, bool dark)
        {
            bool system = s.Mode == GlassMode.SystemAcrylic;
            string r = s.CornerRadius.ToString("0.##", CultureInfo.InvariantCulture);

            // 文字与装饰配色
            string fg = dark ? "#FFFFFFFF" : "#F2101014";
            string sub = dark ? "#B8FFFFFF" : "#A6101014";
            string faint = dark ? "#40FFFFFF" : "#40101014";
            string sep = dark ? "#2EFFFFFF" : "#26000000";
            string selBg = dark ? "#2EFFFFFF" : "#59FFFFFF";
            string thumb = dark ? "#40FFFFFF" : "#33000000";

            // 插件未接管时（例如着色器不可用）的兜底底色，避免文字落在全透明窗口上
            string fallbackBg = dark ? "#E61C1C20" : "#EBF4F4F7";

            // 系统亚克力模式下由 Flow 用 LightBG/DarkBG 给 DWM 背景着色
            string lightBg = "#4DFFFFFF";
            string darkBg = "#59101014";

            var sb = new StringBuilder();
            sb.AppendLine("<!--");
            sb.AppendLine($"    Name: {ThemeDisplayName}");
            sb.AppendLine($"    IsDark: {(dark ? "True" : "False")}");
            sb.AppendLine($"    HasBlur: {(system ? "True" : "False")}");
            sb.AppendLine("    Generated by Flow.Launcher.Plugin.LiquidGlass. Do not edit: changes are overwritten.");
            sb.AppendLine("-->");
            sb.AppendLine(@"<ResourceDictionary
    xmlns=""http://schemas.microsoft.com/winfx/2006/xaml/presentation""
    xmlns:x=""http://schemas.microsoft.com/winfx/2006/xaml""
    xmlns:system=""clr-namespace:System;assembly=mscorlib"">
    <ResourceDictionary.MergedDictionaries>
        <ResourceDictionary Source=""pack://application:,,,/Themes/Base.xaml"" />
    </ResourceDictionary.MergedDictionaries>");

            if (system)
            {
                sb.AppendLine($@"    <system:Boolean x:Key=""ThemeBlurEnabled"">True</system:Boolean>
    <system:String x:Key=""SystemBG"">{(dark ? "Dark" : "Light")}</system:String>
    <Color x:Key=""LightBG"">{lightBg}</Color>
    <Color x:Key=""DarkBG"">{darkBg}</Color>");
            }

            string borderBg = system ? "Transparent" : fallbackBg;
            string borderRadius = system ? "0" : r;

            sb.AppendLine($@"
    <Style x:Key=""WindowRadius"" TargetType=""{{x:Type Border}}"">
        <Setter Property=""CornerRadius"" Value=""{borderRadius}"" />
    </Style>
    <Style x:Key=""ItemGlyph"" BasedOn=""{{StaticResource BaseGlyphStyle}}"" TargetType=""{{x:Type TextBlock}}"">
        <Setter Property=""Foreground"" Value=""{fg}"" />
    </Style>
    <Style x:Key=""QueryBoxStyle"" BasedOn=""{{StaticResource BaseQueryBoxStyle}}"" TargetType=""{{x:Type TextBox}}"">
        <Setter Property=""Padding"" Value=""0 0 50 0"" />
        <Setter Property=""Foreground"" Value=""{fg}"" />
        <Setter Property=""CaretBrush"" Value=""{fg}"" />
        <Setter Property=""Background"" Value=""Transparent"" />
        <Setter Property=""FontSize"" Value=""22"" />
        <Setter Property=""Height"" Value=""44"" />
    </Style>
    <Style x:Key=""QuerySuggestionBoxStyle"" BasedOn=""{{StaticResource BaseQuerySuggestionBoxStyle}}"" TargetType=""{{x:Type TextBox}}"">
        <Setter Property=""Padding"" Value=""0 0 50 0"" />
        <Setter Property=""Background"" Value=""Transparent"" />
        <Setter Property=""FontSize"" Value=""22"" />
        <Setter Property=""Height"" Value=""44"" />
        <Setter Property=""Foreground"" Value=""{faint}"" />
    </Style>
    <Style x:Key=""WindowBorderStyle"" BasedOn=""{{StaticResource BaseWindowBorderStyle}}"" TargetType=""{{x:Type Border}}"">
        <Setter Property=""BorderThickness"" Value=""0"" />
        <Setter Property=""BorderBrush"" Value=""Transparent"" />
        <Setter Property=""Background"" Value=""{borderBg}"" />
        <Setter Property=""CornerRadius"" Value=""{borderRadius}"" />
        <Setter Property=""UseLayoutRounding"" Value=""True"" />
    </Style>
    <Style x:Key=""WindowStyle"" BasedOn=""{{StaticResource BaseWindowStyle}}"" TargetType=""{{x:Type Window}}"" />
    <Style x:Key=""PendingLineStyle"" BasedOn=""{{StaticResource BasePendingLineStyle}}"" TargetType=""{{x:Type Line}}"" />

    <Style x:Key=""ItemTitleStyle"" BasedOn=""{{StaticResource BaseItemTitleStyle}}"" TargetType=""{{x:Type TextBlock}}"">
        <Setter Property=""Foreground"" Value=""{fg}"" />
    </Style>
    <Style x:Key=""ItemSubTitleStyle"" BasedOn=""{{StaticResource BaseItemSubTitleStyle}}"" TargetType=""{{x:Type TextBlock}}"">
        <Setter Property=""Foreground"" Value=""{sub}"" />
    </Style>
    <Style x:Key=""SeparatorStyle"" BasedOn=""{{StaticResource BaseSeparatorStyle}}"" TargetType=""{{x:Type Rectangle}}"">
        <Setter Property=""Fill"" Value=""{sep}"" />
        <Setter Property=""Height"" Value=""1"" />
        <Setter Property=""Margin"" Value=""16 0 16 8"" />
    </Style>
    <Style x:Key=""HighlightStyle"" />
    <Style x:Key=""ItemTitleSelectedStyle"" BasedOn=""{{StaticResource BaseItemTitleSelectedStyle}}"" TargetType=""{{x:Type TextBlock}}"">
        <Setter Property=""Foreground"" Value=""{fg}"" />
    </Style>
    <Style x:Key=""ItemSubTitleSelectedStyle"" BasedOn=""{{StaticResource BaseItemSubTitleSelectedStyle}}"" TargetType=""{{x:Type TextBlock}}"">
        <Setter Property=""Foreground"" Value=""{sub}"" />
    </Style>
    <SolidColorBrush x:Key=""ItemSelectedBackgroundColor"">{selBg}</SolidColorBrush>

    <Style x:Key=""ThumbStyle"" BasedOn=""{{StaticResource BaseThumbStyle}}"" TargetType=""{{x:Type Thumb}}"">
        <Setter Property=""Template"">
            <Setter.Value>
                <ControlTemplate TargetType=""{{x:Type Thumb}}"">
                    <Border Background=""{thumb}"" BorderBrush=""Transparent"" BorderThickness=""0"" CornerRadius=""3"" DockPanel.Dock=""Right"" />
                </ControlTemplate>
            </Setter.Value>
        </Setter>
    </Style>
    <Style x:Key=""ScrollBarStyle"" BasedOn=""{{StaticResource BaseScrollBarStyle}}"" TargetType=""{{x:Type ScrollBar}}"" />
    <Style x:Key=""HorizontalScrollBarStyle"" BasedOn=""{{StaticResource BaseHorizontalScrollBarStyle}}"" TargetType=""{{x:Type ScrollBar}}"" />
    <Style x:Key=""HorizontalThumbStyle"" BasedOn=""{{StaticResource BaseHorizontalThumbStyle}}"" TargetType=""{{x:Type Thumb}}"">
        <Setter Property=""Template"">
            <Setter.Value>
                <ControlTemplate TargetType=""{{x:Type Thumb}}"">
                    <Border Background=""{thumb}"" BorderBrush=""Transparent"" BorderThickness=""0"" CornerRadius=""3"" />
                </ControlTemplate>
            </Setter.Value>
        </Setter>
    </Style>
    <Style x:Key=""SearchIconStyle"" BasedOn=""{{StaticResource BaseSearchIconStyle}}"" TargetType=""{{x:Type Path}}"">
        <Setter Property=""Fill"" Value=""{sub}"" />
        <Setter Property=""Width"" Value=""24"" />
        <Setter Property=""Height"" Value=""24"" />
    </Style>
    <Style x:Key=""SearchIconPosition"" TargetType=""{{x:Type Canvas}}"">
        <Setter Property=""Background"" Value=""Transparent"" />
        <Setter Property=""Width"" Value=""32"" />
        <Setter Property=""Height"" Value=""32"" />
        <Setter Property=""Margin"" Value=""0 10 12 0"" />
        <Setter Property=""HorizontalAlignment"" Value=""Right"" />
    </Style>

    <Style x:Key=""ItemHotkeyStyle"" TargetType=""{{x:Type TextBlock}}"">
        <Setter Property=""FontSize"" Value=""12"" />
        <Setter Property=""Foreground"" Value=""{sub}"" />
    </Style>
    <Style x:Key=""ItemHotkeySelectedStyle"" TargetType=""{{x:Type TextBlock}}"">
        <Setter Property=""FontSize"" Value=""12"" />
        <Setter Property=""Foreground"" Value=""{sub}"" />
    </Style>
    <Style x:Key=""ItemGlyphSelectedStyle"" TargetType=""{{x:Type TextBlock}}"">
        <Setter Property=""Foreground"" Value=""{fg}"" />
        <Setter Property=""VerticalAlignment"" Value=""Center"" />
        <Setter Property=""HorizontalAlignment"" Value=""Center"" />
        <Setter Property=""Width"" Value=""25"" />
        <Setter Property=""Height"" Value=""25"" />
        <Setter Property=""FontSize"" Value=""25"" />
    </Style>
    <CornerRadius x:Key=""ItemRadius"">12</CornerRadius>
    <Thickness x:Key=""ItemMargin"">10 0 10 0</Thickness>
    <Thickness x:Key=""ResultMargin"">0 0 0 10</Thickness>
    <Style x:Key=""ClockPanel"" BasedOn=""{{StaticResource BaseClockPanel}}"" TargetType=""{{x:Type StackPanel}}"">
        <Setter Property=""Margin"" Value=""0 0 54 0"" />
    </Style>
    <Style x:Key=""ClockBox"" BasedOn=""{{StaticResource BaseClockBox}}"" TargetType=""{{x:Type TextBlock}}"">
        <Setter Property=""Foreground"" Value=""{sub}"" />
    </Style>
    <Style x:Key=""DateBox"" BasedOn=""{{StaticResource BaseDateBox}}"" TargetType=""{{x:Type TextBlock}}"">
        <Setter Property=""Foreground"" Value=""{sub}"" />
    </Style>
    <Style x:Key=""PreviewBorderStyle"" BasedOn=""{{StaticResource BasePreviewBorderStyle}}"" TargetType=""{{x:Type Border}}"">
        <Setter Property=""Margin"" Value=""0 0 10 8"" />
        <Setter Property=""BorderBrush"" Value=""{sep}"" />
    </Style>
    <Style x:Key=""PreviewItemTitleStyle"" BasedOn=""{{StaticResource BasePreviewItemTitleStyle}}"" TargetType=""{{x:Type TextBlock}}"">
        <Setter Property=""Foreground"" Value=""{fg}"" />
    </Style>
    <Style x:Key=""PreviewItemSubTitleStyle"" BasedOn=""{{StaticResource BasePreviewItemSubTitleStyle}}"" TargetType=""{{x:Type TextBlock}}"">
        <Setter Property=""Foreground"" Value=""{sub}"" />
    </Style>
    <Style x:Key=""PreviewGlyph"" BasedOn=""{{StaticResource BasePreviewGlyph}}"" TargetType=""{{x:Type TextBlock}}"">
        <Setter Property=""Foreground"" Value=""{fg}"" />
    </Style>
</ResourceDictionary>");
            return sb.ToString();
        }
    }
}
